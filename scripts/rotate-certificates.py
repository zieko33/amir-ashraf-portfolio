#!/usr/bin/env python3
"""Rotate source certificate PDFs 90 degrees left and rebuild upright previews.

Requires Ghostscript, Poppler (pdftoppm), and FFmpeg. Original PDFs are backed up
once, so rerunning rebuilds from the same source instead of rotating twice.
"""

import glob
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parent.parent
AWARDS = ROOT / "public" / "awards"
ORIGINALS = ROOT / ".certificate-originals"
METADATA = ROOT / "src" / "certificateImages.ts"


def executable(name, nix_pattern, version_flag):
    """Prefer PATH; also support this project's Nix development environment."""
    candidates = [shutil.which(name)] + sorted(glob.glob(nix_pattern))
    if name == "gs":
        candidates.insert(1, shutil.which("gswin64c"))
    for candidate in candidates:
        if not candidate:
            continue
        try:
            check = subprocess.run(
                [candidate, version_flag], capture_output=True, timeout=10
            )
            if check.returncode == 0:
                return candidate
        except (OSError, subprocess.TimeoutExpired):
            continue
    raise RuntimeError(
        f"Missing {name}. Install Ghostscript, Poppler, and FFmpeg and add them to PATH."
    )


def run(arguments):
    result = subprocess.run(arguments, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip())


def main():
    sources = sorted(AWARDS.glob("*.pdf"))
    if not sources:
        raise RuntimeError(f"No certificate PDFs found in {AWARDS}")
    gs = executable("gs", "/nix/store/*-ghostscript-*/bin/gs", "-v")
    render = executable("pdftoppm", "/nix/store/*-poppler-utils-*/bin/pdftoppm", "-v")
    ffmpeg = executable("ffmpeg", "/nix/store/*-ffmpeg-*/bin/ffmpeg", "-version")
    ORIGINALS.mkdir(exist_ok=True)
    metadata = {}
    previous = {}
    if METADATA.exists():
        previous = json.loads(METADATA.read_text(encoding="utf-8").split(" = ", 1)[1])

    # Prepare every result before replacing any of the site's current assets.
    with tempfile.TemporaryDirectory(prefix="certificate-rotation-", dir=ROOT) as folder:
        staging = Path(folder)
        for current in sources:
            original = ORIGINALS / current.name
            # A fresh checkout includes the upright assets but not ignored backups.
            # Recognize those assets so running the script there cannot rotate twice.
            already_upright = (
                not original.exists()
                and previous.get(current.stem, {}).get("pdfVersion")
                == hashlib.sha256(current.read_bytes()).hexdigest()[:12]
            )
            if not original.exists() and not already_upright:
                shutil.copyfile(current, original)
            output = staging / current.name
            preview = staging / f"{current.stem}.webp"
            png_stem = staging / current.stem
            if already_upright:
                shutil.copyfile(current, output)
            else:
                run([
                    gs, "-q", "-dBATCH", "-dNOPAUSE", "-dSAFER",
                    "-sDEVICE=pdfwrite", "-dAutoRotatePages=/None",
                    f"-sOutputFile={output}",
                    "-c", "[ /Rotate 270 /PAGES pdfmark", "-f", str(original),
                ])
            run([
                render, "-f", "1", "-singlefile", "-scale-to", "1000", "-png",
                str(output), str(png_stem),
            ])
            png = png_stem.with_suffix(".png")
            header = png.read_bytes()[:24]
            if header[:8] != b"\x89PNG\r\n\x1a\n":
                raise RuntimeError(f"Invalid rendered preview: {png.name}")
            width, height = struct.unpack(">II", header[16:24])
            run([
                ffmpeg, "-hide_banner", "-loglevel", "error", "-i", str(png),
                "-c:v", "libwebp", "-quality", "85", "-y", str(preview),
            ])
            metadata[current.stem] = {
                "width": width,
                "height": height,
                "imageVersion": hashlib.sha256(preview.read_bytes()).hexdigest()[:12],
                "pdfVersion": hashlib.sha256(output.read_bytes()).hexdigest()[:12],
            }
            action = "already upright" if already_upright else "90° left"
            print(f"Prepared {current.name}: {action}, preview {width}×{height}")

        manifest = staging / "certificateImages.ts"
        manifest.write_text(
            "// Generated by scripts/rotate-certificates.py.\n"
            "export interface CertificateImage {\n"
            "  width: number\n  height: number\n"
            "  imageVersion: string\n  pdfVersion: string\n}\n\n"
            "export const certificateImages: Record<string, CertificateImage> = "
            + json.dumps(metadata, indent=2) + "\n",
            encoding="utf-8",
        )
        for current in sources:
            os.replace(staging / current.name, current)
            os.replace(staging / f"{current.stem}.webp", AWARDS / f"{current.stem}.webp")
        os.replace(manifest, METADATA)
    print(f"Updated {len(sources)} PDFs, previews, and image dimensions.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError) as error:
        raise SystemExit(f"Certificate rotation failed: {error}") from error
